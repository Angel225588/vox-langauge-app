let anthropicClient: Anthropic | null = null;

/**
 * Checks if the Anthropic API key is configured.
 * Returns true if the key is available, false otherwise.
 */
export function isClaudeAvailable(): boolean {
  return !!process.env.ANTHROPIC_API_KEY;
}

/**
 * Initializes the Anthropic client.
 * Returns null if API key is not configured (graceful fallback).
 */
function getClient(): Anthropic | null {
  if (anthropicClient) {
    return anthropicClient;
  }

  const apiKey = process.env.ANTHROPIC_API_KEY;

  if (!apiKey) {
    console.warn(
      '[ClaudeClient] ANTHROPIC_API_KEY not configured. ' +
        'Claude features will be disabled, falling back to Gemini-only mode.'
    );
    return null;
  }

  anthropicClient = new Anthropic({
    apiKey,
  });

  return anthropicClient;
}

