/**
 * System prompt for learning path planning.
 * Establishes Claude's role as an expert language learning curriculum designer.
 */
const LEARNING_PATH_SYSTEM_PROMPT = `You are an expert language learning curriculum designer with deep knowledge of CEFR standards, spaced repetition, and second language acquisition research.

Your role is to create strategic learning path plans that will be used to generate detailed content. You should:

1. Analyze the user's profile (native language, target language, current level, goals, interests)
2. Design a progression that builds on previous knowledge
3. Create specific briefs for each "stair" (learning unit) with clear constraints
4. Ensure vocabulary and grammar are appropriate for the user's level
5. Include communicative goals that align with user motivations

Always respond with valid JSON matching the LearningPathPlan schema.`;

/**
 * Generates a strategic learning path plan based on user profile.
 * This is the primary function for Claude's supervisor role in the orchestration.
 *
 * Claude analyzes the user profile and creates a strategic plan with briefs
 * for each stair. These briefs are then used by Gemini to generate the actual
 * content (vocabulary, sentences, quizzes, etc.).
 *
 * @param profile - User's learning profile with preferences and level
 * @returns A complete LearningPathPlan, or null if Claude is unavailable
 * @throws {ClaudeError} If generation or validation fails
 */
export async function generateLearningPathPlan(
  profile: UserLearningProfile
): Promise<LearningPathPlan | null> {
  // Check if Claude is available
  if (!isClaudeAvailable()) {
    console.warn(
      '[ClaudeClient] Claude not available for learning path planning. ' +
        'Falling back to Gemini-only mode.'
    );
    return null;
  }

  const prompt = `Create a personalized learning path plan for a language learner with the following profile:

## User Profile
- Native Language: ${profile.nativeLanguage}
- Target Language: ${profile.targetLanguage}
- Current Level: ${profile.currentLevel}
- Learning Goals: ${profile.learningGoals.join(', ')}
- Interests: ${profile.interests.join(', ')}
- Daily Practice Time: ${profile.dailyTimeMinutes} minutes
${profile.motivation ? `- Motivation: ${profile.motivation}` : ''}
${profile.timeline ? `- Timeline: ${profile.timeline}` : ''}

## Requirements
1. Create 6-10 stairs (learning units) appropriate for their level
2. Each stair should focus on a specific theme related to their interests
3. Include vocabulary, grammar patterns, and communicative goals for each stair
4. Set appropriate constraints (word frequency bands, sentence lengths)
5. Ensure smooth progression from current level

## Output Format
Return a JSON object with this structure:
{
  "userId": "string",
  "totalStairs": number,
  "estimatedDuration": "string (e.g., '4 weeks')",
  "stairs": [
    {
      "id": "stair_1",
      "position": 1,
      "theme": "string",
      "cefrLevel": "string (e.g., 'A1')",
      "vocabularyFocus": ["word1", "word2", ...],
      "grammarPatterns": ["pattern1", "pattern2", ...],
      "communicativeGoals": ["goal1", "goal2", ...],
      "constraints": {
        "wordFrequencyBand": [1, 3000],
        "maxSentenceLength": 10,
        "avoidTopics": []
      }
    }
  ],
  "progressionLogic": "Description of how the path builds skills progressively"
}`;

  try {
    const plan = await generateJSON<LearningPathPlan>(
      prompt,
      LEARNING_PATH_SYSTEM_PROMPT
    );

    if (!plan) {
      return null;
    }

    // Add metadata
    plan.metadata = {
      generatedAt: new Date().toISOString(),
      modelVersion: CLAUDE_CONFIG.model,
    };

    // Validate the plan structure
    validateLearningPathPlan(plan);

    return plan;
  } catch (error: any) {
    if (error instanceof ClaudeError) {
      throw error;
    }

    throw new ClaudeError(
      `Learning path plan generation failed: ${error.message}`,
      'PLAN_GENERATION_FAILED',
      false
    );
  }
}

/**
 * Validates that a learning path plan has the required structure.
 * @throws {ClaudeError} If validation fails
 */
function validateLearningPathPlan(plan: LearningPathPlan): void {
  if (!plan.stairs || plan.stairs.length === 0) {
    throw new ClaudeError(
      'Learning path plan must contain at least one stair',
      'INVALID_PLAN_STRUCTURE',
      false
    );
  }

  if (plan.totalStairs !== plan.stairs.length) {
    throw new ClaudeError(
      `totalStairs (${plan.totalStairs}) does not match stairs array length (${plan.stairs.length})`,
      'INVALID_PLAN_STRUCTURE',
      false
    );
  }

  // Validate each stair has required fields
  for (const stair of plan.stairs) {
    if (!stair.id || !stair.theme || !stair.cefrLevel) {
      throw new ClaudeError(
        `Stair at position ${stair.position} is missing required fields`,
        'INVALID_STAIR_STRUCTURE',
        false
      );
    }

    if (
      !Array.isArray(stair.vocabularyFocus) ||
      !Array.isArray(stair.grammarPatterns) ||
      !Array.isArray(stair.communicativeGoals)
    ) {
      throw new ClaudeError(
        `Stair "${stair.id}" has invalid array fields`,
        'INVALID_STAIR_STRUCTURE',
        false
      );
    }
  }
}

