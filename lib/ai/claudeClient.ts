/**
 * Anthropic Claude API Client for Vox Language App
 *
 * This module provides a robust interface to Anthropic's Claude API,
 * with retry logic, error handling, and typed response parsing for
 * learning path planning and orchestration.
 *
 * In the Claude + Gemini orchestration architecture, Claude acts as the
 * supervisor (strategic planning, validation, quality control) while
 * Gemini Flash acts as the worker (bulk content generation).
 */

import Anthropic from '@anthropic-ai/sdk';

// ============================================================================
// TYPE DEFINITIONS
// ============================================================================

/**
 * User's learning profile used for generating personalized learning paths.
 * This is the primary input for Claude's strategic planning.
 */
export interface UserLearningProfile {
  /** User's native/fluent language (e.g., 'en', 'es') */
  nativeLanguage: string;
  /** Target language being learned (e.g., 'es', 'fr', 'de') */
  targetLanguage: string;
  /** Current CEFR proficiency level */
  currentLevel: 'A1' | 'A2' | 'B1' | 'B2' | 'C1' | 'C2';
  /** User's specific learning goals */
  learningGoals: string[];
  /** User's interests for content personalization */
  interests: string[];
  /** Daily available practice time in minutes */
  dailyTimeMinutes: number;
  /** Optional: User's motivation for learning */
  motivation?: string;
  /** Optional: User's timeline (e.g., '3_months', '6_months') */
  timeline?: string;
}

/**
 * Brief for a single stair/step in the learning path.
 * Claude generates these briefs, which Gemini then uses to generate content.
 */
export interface StairBrief {
  /** Unique identifier for the stair */
  id: string;
  /** Position in the learning path (1-indexed) */
  position: number;
  /** Thematic focus (e.g., 'Greetings', 'Food', 'Travel') */
  theme: string;
  /** Target CEFR level for this stair */
  cefrLevel: string;
  /** Focus vocabulary words/phrases to include */
  vocabularyFocus: string[];
  /** Grammar patterns to practice */
  grammarPatterns: string[];
  /** Communication goals for this stair */
  communicativeGoals: string[];
  /** Constraints for content generation */
  constraints: {
    /** Word frequency band range (e.g., [1, 3000] for top 3000 words) */
    wordFrequencyBand: [number, number];
    /** Maximum sentence length in words */
    maxSentenceLength: number;
    /** Topics to avoid in generated content */
    avoidTopics: string[];
  };
}

/**
 * Complete learning path plan generated by Claude.
 * Contains strategic structure and briefs for Gemini to execute.
 */
export interface LearningPathPlan {
  /** User ID this plan is for */
  userId: string;
  /** Total number of stairs in the path */
  totalStairs: number;
  /** Estimated duration to complete (e.g., '4 weeks', '2 months') */
  estimatedDuration: string;
  /** Array of stair briefs for content generation */
  stairs: StairBrief[];
  /** Description of the progression logic used */
  progressionLogic: string;
  /** Metadata about generation */
  metadata?: {
    generatedAt: string;
    modelVersion: string;
  };
}

