// CORE GENERATION FUNCTIONS
// ============================================================================

/**
 * Sends a prompt to Claude and returns the raw text response.
 * Includes retry logic with exponential backoff for transient failures.
 *
 * @param prompt - The prompt to send to Claude
 * @param systemPrompt - Optional system prompt for context
 * @returns The raw text response from Claude, or null if Claude is unavailable
 * @throws {ClaudeError} If all retry attempts fail or a non-retryable error occurs
 */
export async function generateWithClaude(
  prompt: string,
  systemPrompt?: string
): Promise<string | null> {
  const client = getClient();

  if (!client) {
    // Graceful fallback - Claude not available
    return null;
  }

  let lastError: any;

  for (let attempt = 0; attempt < RETRY_CONFIG.maxAttempts; attempt++) {
    try {
      const message = await client.messages.create({
        model: CLAUDE_CONFIG.model,
        max_tokens: CLAUDE_CONFIG.maxTokens,
        ...(systemPrompt && { system: systemPrompt }),
        messages: [
          {
            role: 'user',
            content: prompt,
          },
        ],
      });

      // Extract text from the response
      const textBlock = message.content.find(block => block.type === 'text');
      if (!textBlock || textBlock.type !== 'text') {
        throw new ClaudeError(
          'Claude returned a response without text content',
          'EMPTY_RESPONSE',
          true
        );
      }

      return textBlock.text;
    } catch (error: any) {
      lastError = error;

      const isRetryable = isRetryableError(error);
      const isRateLimit = error.status === 429;

      // If not retryable or last attempt, throw
      if (!isRetryable || attempt === RETRY_CONFIG.maxAttempts - 1) {
        throw new ClaudeError(
          `Claude API error: ${error.message}`,
          error.code || error.error?.type || 'UNKNOWN_ERROR',
          isRetryable
        );
      }

      // Calculate delay and retry
      const delay = calculateDelay(attempt, isRateLimit);
      console.warn(
        `[ClaudeClient] Request failed (attempt ${attempt + 1}/${RETRY_CONFIG.maxAttempts}). ` +
          `Retrying in ${delay}ms... Error: ${error.message}`
      );

      await sleep(delay);
    }
  }

  // This should never be reached due to the throw in the loop
  throw new ClaudeError(
    `Failed after ${RETRY_CONFIG.maxAttempts} attempts: ${lastError?.message}`,
    lastError?.code || 'MAX_RETRIES_EXCEEDED',
    false
  );
}

/**
 * Generates content with Claude and parses the response as JSON.
 * Automatically extracts JSON from markdown code blocks if present.
 *
 * @param prompt - The prompt to send to Claude
 * @param systemPrompt - Optional system prompt for context
 * @returns Parsed JSON object of type T, or null if Claude is unavailable
 * @throws {ClaudeError} If generation fails or JSON parsing fails
 */
export async function generateJSON<T>(
  prompt: string,
  systemPrompt?: string
): Promise<T | null> {
  const rawResponse = await generateWithClaude(prompt, systemPrompt);

  if (rawResponse === null) {
    // Claude not available - graceful fallback
    return null;
  }

  try {
    // Try to extract JSON from markdown code blocks
    const jsonMatch = rawResponse.match(/```(?:json)?\s*([\s\S]*?)```/);
    const jsonString = jsonMatch ? jsonMatch[1].trim() : rawResponse.trim();

    return JSON.parse(jsonString) as T;
  } catch (error: any) {
    throw new ClaudeError(
      `Failed to parse Claude response as JSON: ${error.message}`,
      'INVALID_JSON',
      false
    );
  }
}

