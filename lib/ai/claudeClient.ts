// CONFIGURATION
// ============================================================================

const CLAUDE_CONFIG = {
  /** Default model - Claude Opus 4.5 for highest quality strategic planning */
  model: process.env.CLAUDE_MODEL || 'claude-opus-4-5-20251101',
  /** Maximum tokens for response */
  maxTokens: 4096,
  /** Temperature for controlled creativity */
  temperature: 0.7,
};

const RETRY_CONFIG = {
  maxAttempts: 3,
  baseDelayMs: 1000,
  maxDelayMs: 10000,
};

// ============================================================================
// ERROR HANDLING
// ============================================================================

/**
 * Custom error class for Claude API errors.
 * Includes information about whether the error is retryable.
 */
export class ClaudeError extends Error {
  constructor(
    message: string,
    public code: string,
    public retryable: boolean
  ) {
    super(message);
    this.name = 'ClaudeError';
  }
}

/**
 * Determines if an error is retryable based on its type.
 */
function isRetryableError(error: any): boolean {
  // Network errors
  if (error.code === 'NETWORK_ERROR' || error.code === 'ENOTFOUND') {
    return true;
  }

  // Rate limiting (429)
  if (error.status === 429) {
    return true;
  }

  // Server errors (5xx)
  if (error.status >= 500 && error.status < 600) {
    return true;
  }

  // Timeout errors
  if (error.code === 'ETIMEDOUT' || error.code === 'TIMEOUT') {
    return true;
  }

  // Anthropic-specific overload errors
  if (error.error?.type === 'overloaded_error') {
    return true;
  }

  return false;
}

/**
 * Calculates exponential backoff delay with jitter.
 */
function calculateDelay(attempt: number, isRateLimit: boolean = false): number {
  const baseDelay = isRateLimit
    ? RETRY_CONFIG.baseDelayMs * 3 // Longer delay for rate limits
    : RETRY_CONFIG.baseDelayMs;

  const exponentialDelay = baseDelay * Math.pow(2, attempt);
  const jitter = Math.random() * 1000;

  return Math.min(exponentialDelay + jitter, RETRY_CONFIG.maxDelayMs);
}

/**
 * Sleep utility for retry delays.
 */
function sleep(ms: number): Promise<void> {
  return new Promise(resolve => setTimeout(resolve, ms));
}

